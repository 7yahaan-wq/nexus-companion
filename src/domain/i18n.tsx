export function translate(language: string, text: string, english?: string) {
  return language === 'en' ? english || en[text] || text : zh[text] || text;
}
export function useI18n() {
  const language = useContext(LanguageContext);
  return { language, t: (text: string, english?: string) => translate(language, text, english) };
}
export function L({ text }: { text: string }) {
  const { t } = useI18n();
  return <>{t(text)}</>;
}
